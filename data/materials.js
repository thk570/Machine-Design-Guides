// Machine Design Guides — shared material property library, source of truth for any calculator
// that needs material properties (interference-fit force estimates, thermal-fit sizing, structural
// checks, creepage/clearance material-group lookups, ...). Plain JS (not .json), loaded via
// <script src="../../data/materials.js"> from a page that needs it — same reasoning as
// data/manifest.js: a <script src> tag isn't subject to the same-origin/CORS block that fetch()
// hits under file://, so this still works by double-clicking index.html or any calculator page
// straight off the filesystem. See docs/00-structure-and-conventions.md ("Shared material library")
// for the convention this file follows and how a page should consume it.
//
// Arranged MMPDS-style: material type (class) -> grade/condition. Not a reproduction of MMPDS itself
// (a paywalled, statistically-derived allowables handbook). Rows with basis "MMPDS S-basis" / "A-basis"
// / "B-basis" were re-keyed by hand from MMPDS-14 design tables (cited per row in `refs`), converted to
// metric, L (longitudinal) direction unless the notes say otherwise; the handbook's full allowables are
// not reproduced. The other rows trace to a datasheet (`basis`: "Datasheet", "Spec min" for a specification
// minimum, "Typical" for a generic or single-source typical value), cited per grade in `refs`.
//
// `typical` (optional array of property names, e.g. ["G_GPa","poisson"]) lists the values on a grade that
// are generic family constants rather than that grade's own data; the page shows them in italics. Properties
// MMPDS prints only as graphs (mostly CTE, k, melting range) are either omitted or filled from the library's
// existing entry for the same alloy and listed in `typical`.
//
// Optional per-grade fields: `basis` (see above), `aka` (same material under another designation or trade
// name), `similar` (closest equivalent only, not interchangeable), and a cost band: `cost_band` 1-5 is the
// approximate GBP/kg of a small-lot stock piece, ex VAT, form and supply counted (1 under 6, 2 6-12,
// 3 12-30, 4 30-70, 5 over 70); `cost_est` true marks an estimate with no source price; `cost_note` says how
// it was set; `cost_ref` is the price source. Cost bands are not live and need re-checking from time to time.
// Pages must tolerate any optional field being absent. A grade with no published yield strength (hardened
// M2) has `"yield_MPa": null`; consumers must treat null as "N/A", never as zero.
//
// Order: grades are kept sorted alphanumerically within each type (grade, then condition) — pages
// render in file order, so insert new grades in sequence. Insulating materials stay ordered by CTI
// group (I → IIIb) instead.
//
// `conductivity_pct_IACS` (present on the copper/aluminium conductor grades) is what the Busbar
// Sizing calculator uses to pick which grades count as "conductor grade" — it filters the material
// select to grades that have this field rather than hard-coding a grade-id list, so a future grade
// added here with a conductivity value is picked up automatically. `specific_heat_J_per_kgK` is
// present on those same conductor grades and is what that calculator's transient-overload check
// uses for the adiabatic heating calculation — like conductivity, it's simply omitted on grades
// nothing here needs it for.
//
// The `insulating-materials` type is a different kind of entry: dielectrics (polymers, laminates,
// ceramics) used for creepage/clearance insulation design. They carry `cti_V` / `cti_range` (Comparative
// Tracking Index, IEC 60112) and `cti_group` (the IEC 60664-1 material group — I/II/IIIa/IIIb — that CTI
// falls into), plus the same mechanical and physical fields as the metals (density, E, G, ν, yield, UTS,
// CTE, k, specific heat, melting range) and these extra optional fields: `tg_C` (glass transition),
// `max_service_C` (maximum continuous service temperature), `dielectric_strength_kV_per_mm` (+
// `dielectric_cond`, test thickness/standard), `volume_resistivity_ohm_m`, `permittivity_rel` (+
// `permittivity_cond`, frequency). `lower_bound` (array of property names) marks values the source prints
// as a minimum or floor (">"); `typical` works as above, and G is derived from E and ν (so listed in
// `typical`). `yield_MPa: null` means no true yield (brittle or elastomer); `ultimate_MPa: null` means no
// value found. Both keys are always present on these grades so consumers never see undefined. Values are
// typical datasheet figures for the unfilled or named grade at about 23 °C; `props_note` carries the
// caveats for the property set. The Creepage & Clearance calculator's substrate-material lookup filters
// this library to grades with `cti_group` set, rather than hard-coding its own material list, the same
// way the Busbar calculator filters on `conductivity_pct_IACS`.
